// Run: node pilot/scripts/derive-state-map.mjs > pilot/STATE-MAP.generated.md
// Derives, from the code, what each page can call and which gates it reacts to. Nothing here is hand-written:
// re-run it whenever pages change; diff against the committed copy to see new calls/states appear.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const src = path.join(root, "src");
const rel = (f) => path.relative(root, f);
const exists = (f) => fs.existsSync(f) && fs.statSync(f).isFile();

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = path.join(src, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(from), spec);
  else return null;
  for (const c of [base + ".tsx", base + ".ts", path.join(base, "index.tsx"), path.join(base, "index.ts"), base]) if (exists(c)) return c;
  return null;
}
function closure(entry) {
  const seen = new Set(), stack = [entry];
  while (stack.length) {
    const f = stack.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    const t = fs.readFileSync(f, "utf8");
    for (const m of t.matchAll(/(?:import|export)[^'"]*?from\s*["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g)) {
      const r = resolveImport(f, m[1] || m[2]);
      if (r && !r.includes("/api/") && !r.includes("/src/pilot/")) stack.push(r);
    }
  }
  return seen;
}
function fetchesIn(f) {
  const t = fs.readFileSync(f, "utf8");
  const out = [];
  for (const m of t.matchAll(/fetch\(\s*(`[^`]*`|"[^"]*"|'[^']*'|[A-Za-z_.]+)\s*(?:,\s*([\s\S]{0,260}?))?\)/g)) {
    const line = t.slice(0, m.index).split("\n").length;
    let url = m[1].replace(/^[`"']|[`"']$/g, "");
    const opts = m[2] || "";
    const method = (opts.match(/method:\s*["'](\w+)["']/) || [])[1] || "GET";
    if (!url.startsWith("/api/") && !url.startsWith("${") && !/^[A-Za-z_.]+$/.test(m[1]) ) continue;
    out.push({ method, url: url.replace(/\$\{[^}]*\}/g, ":x"), line, dynamic: /^[A-Za-z_.]+$/.test(m[1]) });
  }
  return out;
}
const SIGNALS = [
  ["requireAuth", /requireAuth\(/g], ["useSession", /useSession\(/g], ["openTopUp (credits gate)", /openTopUp\(/g],
  ["402 handling", /status\s*===?\s*402|\.status\s*===?\s*402/g], ["!res.ok / error branch", /!\s*\w+\.ok\b|\.error\b/g],
  ["toast.error", /toast\.error\(/g], ["empty-state copy", /\bno\s+\w+\s+yet\b|nothing here|get started|empty/gi],
  ["loading flag", /\bloading\b|\bisLoading\b|\bbusy\b/g], ["localStorage/sessionStorage", /(local|session)Storage/g],
  ["query-string handoff", /searchParams|useSearchParams|URLSearchParams/g], ["isAdmin gate", /isAdmin/g],
];
const count = (files, re) => files.reduce((n, f) => n + (fs.readFileSync(f, "utf8").match(re) || []).length, 0);

const pages = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (e.name !== "api" && !(d === path.join(src, "app") && e.name === "pilot")) walk(p); } else if (e.name === "page.tsx") pages.push(p);
  }
})(path.join(src, "app"));

const route = (p) => "/" + path.relative(path.join(src, "app"), path.dirname(p)).split(path.sep).filter((s) => !/^\(.*\)$/.test(s)).join("/");
const shellEntries = [path.join(src, "app/(dashboard)/layout.tsx")];
const shellFiles = [...new Set(shellEntries.flatMap((e) => [...closure(e)]))];
const shellKeys = new Set(shellFiles.flatMap(fetchesIn).map((x) => `${x.method} ${x.url}`));

const out = [];
out.push("# STATE-MAP (generated — do not hand-edit)", "", `Generated by pilot/scripts/derive-state-map.mjs from ${pages.length} page files. Every row is a literal call site in the code.`, "");
out.push("## Dashboard shell (mounts on EVERY (dashboard) route)", "",
  "Files in the shell closure: " + shellFiles.length + ". Calls reachable from the shell (some only after a click/modal open):", "",
  "| Call | Where |", "|---|---|");
const shellRows = shellFiles.flatMap((f) => fetchesIn(f).map((x) => ({ ...x, f }))).sort((a, b) => (a.url + a.method).localeCompare(b.url + b.method));
for (const x of shellRows) out.push(`| \`${x.method} ${x.url}\`${x.dynamic ? " (dynamic url)" : ""} | ${rel(x.f)}:${x.line} |`);
out.push("");

for (const p of pages.sort()) {
  const files = [...closure(p)];
  const own = files.filter((f) => !shellFiles.includes(f));
  const rows = own.flatMap((f) => fetchesIn(f).map((x) => ({ ...x, f }))).sort((a, b) => (a.url + a.method).localeCompare(b.url + b.method));
  const isClient = fs.readFileSync(p, "utf8").includes('"use client"');
  out.push(`## ${route(p)}`, "", `- file: \`${rel(p)}\` · ${isClient ? "client component" : "server component"} · ${own.length} page-own files (excl. shell)`);
  if (!isClient) { const redirect = (fs.readFileSync(p, "utf8").match(/redirect\((.*)\);/) || [])[1]; out.push(`- server-side redirect → \`${redirect}\` — no interceptable state`, ""); continue; }
  const sig = SIGNALS.map(([n, re]) => [n, count(own, re)]).filter(([, c]) => c).map(([n, c]) => `${n}×${c}`);
  out.push(`- state signals (counts of code patterns, a reading aid not a spec): ${sig.join(" · ") || "none"}`, "");
  if (!rows.length) { out.push("_No page-own fetches (only shell calls)._", ""); continue; }
  out.push("| Call | Where |", "|---|---|");
  const seen = new Set();
  for (const x of rows) { const k = `${x.method} ${x.url} ${rel(x.f)}:${x.line}`; if (seen.has(k)) continue; seen.add(k); out.push(`| \`${x.method} ${x.url}\`${x.dynamic ? " (dynamic url)" : ""}${shellKeys.has(`${x.method} ${x.url}`) ? " · also in shell" : ""} | ${rel(x.f)}:${x.line} |`); }
  out.push("");
}
process.stdout.write(out.join("\n") + "\n");
