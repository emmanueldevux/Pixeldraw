import nodemailer from "nodemailer";

const transporter = nodemailer.createTransport({
  host: process.env.SMTP_HOST,
  port: parseInt(process.env.SMTP_PORT || "587"),
  secure: false,
  auth: {
    user: process.env.SMTP_USER,
    pass: process.env.SMTP_PASS,
  },
});

export async function sendContentEmail(params: {
  to: string;
  subject: string;
  caption: string;
  imageUrl?: string;
  platform: string;
  brandName: string;
}): Promise<void> {
  const html = `
    <div style="font-family: sans-serif; max-width: 600px; margin: 0 auto;">
      <h2 style="color: #18181B;">🎨 New Content Ready — ${params.brandName}</h2>
      <p style="color: #52525B;">Platform: <strong>${params.platform}</strong></p>
      
      ${params.imageUrl ? `<img src="${params.imageUrl}" alt="Generated content" style="width: 100%; border-radius: 12px; margin: 16px 0;" />` : ""}
      
      <div style="background: #F4F4F5; padding: 16px; border-radius: 8px; margin: 16px 0;">
        <p style="color: #18181B; white-space: pre-wrap;">${params.caption}</p>
      </div>
      
      <p style="color: #A1A1AA; font-size: 12px;">Generated by Uxlly</p>
    </div>
  `;

  await transporter.sendMail({
    from: process.env.EMAIL_FROM,
    to: params.to,
    subject: params.subject,
    html,
  });
}
